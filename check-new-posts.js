#!/usr/bin/env node
/* Weekly check: list blog posts that aren't referenced on the site.
   Prints a markdown report to stdout, or nothing if there's nothing new.
   Slugs listed in known-unpinned.txt are ignored. Node 18+. */

const fs = require('fs');
const path = require('path');

const SITE = 'edwardleartrail.wordpress.com';
const slugOf = u => (u || '').replace(/\/+$/, '').split('/').pop();

(async () => {
  const html = fs.readFileSync(path.join(__dirname, 'index.html'), 'utf8');
  const skip = fs.readFileSync(path.join(__dirname, 'known-unpinned.txt'), 'utf8')
    .split('\n').map(l => l.trim()).filter(l => l && !l.startsWith('#'));
  let posts = [];
  for (let page = 1; page <= 5; page++) {
    const api = `https://public-api.wordpress.com/rest/v1.1/sites/${SITE}/posts/?number=100&page=${page}&fields=URL,title,date`;
    const r = await fetch(api);
    if (!r.ok) { console.error('WordPress API error', r.status); process.exit(1); }
    const j = await r.json();
    posts = posts.concat(j.posts || []);
    if (!j.posts || j.posts.length < 100) break;
  }
  console.error(`Checked ${posts.length} posts.`);
  const fresh = posts.filter(p => {
    const s = slugOf(p.URL);
    return s && !html.includes(s) && !skip.includes(s);
  });
  if (!fresh.length) return;
  console.log('The weekly check found dispatches on the blog that are not on the map yet:\n');
  for (const p of fresh) console.log(`- [${p.title}](${p.URL}) — published ${p.date.slice(0, 10)}`);
  console.log('\nTo add them to the map, open a Claude Code session on this repo and paste this list in. To silence one instead, add its slug to `known-unpinned.txt`.');
  console.log('\n---\n_Generated by [Claude Code](https://claude.ai/code)_');
})();
